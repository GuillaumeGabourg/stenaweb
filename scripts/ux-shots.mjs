// Captures the UX pass: active nav, project images, inline form errors, mobile sticky CTA.
import puppeteer from "puppeteer-core";
const BASE = process.argv[2] ?? "http://localhost:3000";
const OUT = ".impeccable/review";
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const b = await puppeteer.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true });
const p = await b.newPage();
await p.setViewport({ width: 1440, height: 900 });
await p.goto(BASE + "/", { waitUntil: "networkidle2" });
await wait(1000);
await p.click('nav ul a[href="/#realisations"]');
await wait(2200);
await p.screenshot({ path: `${OUT}/ux-nav-work.png` });
console.log("img widths", await p.evaluate(() => [...document.querySelectorAll("#realisations img")].map((i) => i.currentSrc.split("?")[1]?.slice(0, 40) + " " + i.naturalWidth)));
await p.click('nav ul a[href="/#contact"]');
await wait(2200);
await p.click("#name");
await p.click("#email");
await p.type("#email", "jean@");
await p.click("#message");
await wait(300);
await p.click("button[type=submit]");
await wait(800);
await p.screenshot({ path: `${OUT}/ux-form-errors.png` });
console.log("focused:", await p.evaluate(() => document.activeElement?.id), "cursor:", await p.evaluate(() => getComputedStyle(document.querySelector("button[type=submit]")).cursor));
const m = await b.newPage();
await m.setViewport({ width: 390, height: 844, isMobile: true, hasTouch: true });
await m.goto(BASE + "/", { waitUntil: "networkidle2" });
await m.evaluate(() => window.scrollTo(0, 1600));
await wait(1500);
await m.screenshot({ path: `${OUT}/ux-mobile-cta.png` });
await b.close();
